def f(x, digits=4):
    return f"{x:.{digits}f}"

def agg(rows, key):
    out={}
    for r in rows:
        v=r[key]
        out[r['K']]={'mean':v['mean'],'std':v['std'],'ci95_lo':v['ci95_lo'],'ci95_hi':v['ci95_hi']}
    return out

def markdown_table(rows, keys, labels):
    lines=['| ' + ' | '.join(labels) + ' |', '|' + '---|'*len(labels)]
    for r in rows:
        vals=[]
        for k in keys:
            if k=='K': v=str(r['K'])
            elif isinstance(r[k], dict): v=f(r[k]['mean'],2)+' ± '+f(r[k]['std'],2)
            else: v=f(r[k],2)
            vals.append(v)
        lines.append('| ' + ' | '.join(vals) + ' |')
    return '\n'.join(lines)

